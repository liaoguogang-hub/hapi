import { existsSync } from 'node:fs'
import { readdir, readFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { AGENT_MESSAGE_PAYLOAD_TYPE } from '@hapi/protocol'
import type {
    ClaudeImportedMessage,
    ClaudeImportedMessageContent,
    ClaudeImportSession
} from '@hapi/protocol/apiTypes'

/**
 * Reads Claude Code's own transcript store.
 *
 * Claude Code (CLI and the VS Code extension, which share one store) keeps one
 * JSONL file per session under `<CLAUDE_HOME>/projects/<slug>/<sessionId>.jsonl`.
 * The slug encodes the working directory with separators replaced by `-`
 * (`D:\KimiCode` → `D--KimiCode`), which is lossy, so the cwd and title are read
 * from the records themselves instead of the directory name.
 *
 * Each line is one event: `user`, `assistant`, `summary`, `queue-operation`,
 * `attachment`, … Only user/assistant turns are imported. A single assistant
 * message can span several records (one per content block: thinking, text,
 * tool_use), so records sharing a message id are merged and only the text parts
 * survive.
 */

const DEFAULT_LIMIT = 500

export type ClaudeSessionSummary = {
    id: string
    title: string
    cwd: string | null
    updatedAt: number
    filePath: string
}

type JsonRecord = Record<string, unknown>

/** One parsed line of a Claude Code transcript. */
export type ClaudeTranscriptRecord = JsonRecord

function asRecord(value: unknown): JsonRecord | null {
    return value !== null && typeof value === 'object' && !Array.isArray(value)
        ? value as JsonRecord
        : null
}

function asString(value: unknown): string | null {
    return typeof value === 'string' && value.length > 0 ? value : null
}

function asNumber(value: unknown): number | null {
    return typeof value === 'number' && Number.isFinite(value) ? value : null
}

export function getClaudeHome(env: NodeJS.ProcessEnv = process.env): string {
    const configured = env.CLAUDE_CONFIG_DIR?.trim()
    return configured || join(homedir(), '.claude')
}

/** Text of a Claude `message.content`, which is either a string or a block list. */
function textOfContent(content: unknown): string {
    if (typeof content === 'string') return content.trim()
    if (!Array.isArray(content)) return ''
    const parts: string[] = []
    for (const block of content) {
        const record = asRecord(block)
        if (!record) continue
        if (record.type !== 'text') continue
        const text = asString(record.text)
        if (text) parts.push(text.trim())
    }
    return parts.filter((part) => part.length > 0).join('\n\n').trim()
}

/**
 * Claude Code injects machine-generated context into user turns. Importing it
 * would fill the phone's transcript with system reminders that were never typed.
 */
function isInjectedContext(text: string): boolean {
    const head = text.trimStart()
    return head.startsWith('<system-reminder>')
        || head.startsWith('<command-name>')
        || head.startsWith('<local-command')
        || head.startsWith('Caveat: The messages below were generated by the user while running local commands')
}

function parseTimestamp(value: unknown): number | null {
    if (typeof value !== 'string') return null
    const parsed = Date.parse(value)
    return Number.isFinite(parsed) ? parsed : null
}

/** Reads every record of one transcript, ignoring unreadable lines. */
async function readRecords(filePath: string): Promise<JsonRecord[]> {
    let text: string
    try {
        text = await readFile(filePath, 'utf8')
    } catch {
        return []
    }
    const records: JsonRecord[] = []
    for (const line of text.split(/\r?\n/)) {
        const trimmed = line.trim()
        if (!trimmed) continue
        try {
            const parsed = asRecord(JSON.parse(trimmed))
            if (parsed) records.push(parsed)
        } catch {
            // A transcript being written right now can end mid-line.
        }
    }
    return records
}

/** Fields every session summary needs, all derivable from the transcript. */
function summaryFrom(filePath: string, records: JsonRecord[], fallbackId: string): ClaudeSessionSummary | null {
    let cwd: string | null = null
    let firstUserText: string | null = null
    let summaryText: string | null = null
    let createdAt: number | null = null
    let updatedAt: number | null = null
    let sessionId = fallbackId

    for (const record of records) {
        const recordCwd = asString(record.cwd)
        if (recordCwd && !cwd) cwd = recordCwd
        const recordSession = asString(record.sessionId)
        if (recordSession) sessionId = recordSession

        const at = parseTimestamp(record.timestamp)
        if (at !== null) {
            if (createdAt === null || at < createdAt) createdAt = at
            if (updatedAt === null || at > updatedAt) updatedAt = at
        }

        if (record.type === 'summary') {
            const text = asString(record.summary)
            if (text && !summaryText) summaryText = text
            continue
        }
        if (record.type !== 'user' || record.isSidechain === true) continue
        if (!firstUserText) {
            const message = asRecord(record.message)
            const text = textOfContent(message?.content)
            if (text && !isInjectedContext(text)) firstUserText = text
        }
    }

    if (updatedAt === null) return null
    const title = (summaryText ?? firstUserText ?? '').replace(/\s+/g, ' ').trim().slice(0, 60).trim()
    return {
        id: sessionId,
        title: title || `Claude ${sessionId.slice(0, 8)}`,
        cwd,
        updatedAt,
        filePath
    }
}

/**
 * Enumerates the transcripts in Claude's store, newest first.
 *
 * `projects/<slug>/` is scanned rather than trusted for the working directory:
 * the slug is a lossy encoding, while every record carries the real `cwd`.
 */
export async function listClaudeSessions(options?: {
    cwd?: string
    limit?: number
    home?: string
}): Promise<ClaudeSessionSummary[]> {
    const home = options?.home ?? getClaudeHome()
    const projectsRoot = join(home, 'projects')
    if (!existsSync(projectsRoot)) return []

    const wantedCwd = options?.cwd?.replace(/\\/g, '/').replace(/\/+$/, '').toLowerCase()
    const sessions: ClaudeSessionSummary[] = []

    for (const project of await readdir(projectsRoot, { withFileTypes: true })) {
        if (!project.isDirectory()) continue
        const projectDir = join(projectsRoot, project.name)
        let entries
        try {
            entries = await readdir(projectDir, { withFileTypes: true })
        } catch {
            continue
        }
        for (const entry of entries) {
            if (!entry.isFile() || !entry.name.endsWith('.jsonl')) continue
            const filePath = join(projectDir, entry.name)
            const records = await readRecords(filePath)
            if (records.length === 0) continue
            const summary = summaryFrom(filePath, records, entry.name.replace(/\.jsonl$/, ''))
            if (!summary) continue
            if (wantedCwd) {
                const cwd = summary.cwd?.replace(/\\/g, '/').replace(/\/+$/, '').toLowerCase()
                if (cwd !== wantedCwd) continue
            }
            sessions.push(summary)
        }
    }

    sessions.sort((left, right) => right.updatedAt - left.updatedAt)
    return sessions.slice(0, Math.max(1, options?.limit ?? DEFAULT_LIMIT))
}

function importedUser(text: string): ClaudeImportedMessageContent {
    return {
        role: 'user',
        content: { type: 'text', text },
        meta: { sentFrom: 'cli' }
    }
}

function importedAgent(text: string, id: string): ClaudeImportedMessageContent {
    return {
        role: 'agent',
        content: { type: AGENT_MESSAGE_PAYLOAD_TYPE, data: { type: 'message', message: text, id } },
        meta: { sentFrom: 'cli' }
    }
}

/**
 * Maps a Claude Code transcript onto HAPI's imported-message shape.
 *
 * Tool traffic and thinking are dropped: the phone renders neither for imported
 * history, and keeping them would balloon a session the desktop shows as a few
 * turns. Sidechain records belong to subagents and are skipped outright.
 *
 * Local ids are `<prefix><ordinal>`, so a re-import lines up with what the hub
 * already stored and only a genuine tail is appended.
 */
export function mapClaudeTranscriptToMessages(
    claudeSessionId: string,
    records: ClaudeTranscriptRecord[],
    fallbackTime: number
): ClaudeImportedMessage[] {
    const prefix = `claude:${claudeSessionId}:`
    const messages: ClaudeImportedMessage[] = []
    let pendingAssistantId: string | null = null

    for (const record of records) {
        if (record.isSidechain === true) continue
        const type = record.type
        if (type !== 'user' && type !== 'assistant') continue

        const message = asRecord(record.message)
        if (!message) continue
        const text = textOfContent(message.content)
        if (!text) continue
        if (type === 'user' && isInjectedContext(text)) continue

        const at = parseTimestamp(record.timestamp) ?? fallbackTime
        const localId = `${prefix}${messages.length}`

        if (type === 'assistant') {
            // Claude writes one record per content block for the same message;
            // only the text parts survive the filter above, so a repeated id
            // means the previous record already carried this message's text.
            const messageId = asString(message.id)
            if (messageId && messageId === pendingAssistantId) continue
            pendingAssistantId = messageId
            messages.push({ localId, createdAt: at, content: importedAgent(text, localId) })
            continue
        }

        pendingAssistantId = null
        messages.push({ localId, createdAt: at, content: importedUser(text) })
    }

    return messages
}

/** Collapses whitespace so a multi-line prompt does not wrap the phone's list row. */
function toTitle(value: string, limit = 60): string {
    return value.replace(/\s+/g, ' ').trim().slice(0, limit).trim()
}

/** Reads one transcript and packages it for the hub import route. */
export async function readClaudeImportSession(summary: ClaudeSessionSummary): Promise<ClaudeImportSession> {
    const records = await readRecords(summary.filePath)
    const messages = mapClaudeTranscriptToMessages(summary.id, records, summary.updatedAt)
    const firstUser = messages.find((message) => message.content.role === 'user')
    const firstUserText = firstUser && firstUser.content.role === 'user'
        ? toTitle(firstUser.content.content.text)
        : ''
    return {
        claudeSessionId: summary.id,
        title: toTitle(summary.title) || firstUserText || `Claude ${summary.id.slice(0, 8)}`,
        cwd: summary.cwd,
        updatedAt: summary.updatedAt,
        messages
    }
}
